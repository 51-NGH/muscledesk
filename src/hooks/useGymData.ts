import { useQuery, useMutation, useQueryClient } from "@tanstack/react-query";
import { supabase } from "@/integrations/supabase/client";
import { useAuth } from "@/contexts/AuthContext";
import { toast } from "sonner";

// Types
export type MemberStatus = "active" | "expiring_soon" | "expired" | "blocked";
export type PaymentMode = "cash" | "upi" | "card";
export type PaymentStatus = "completed" | "pending" | "failed";
export type ExpenseCategory = "rent" | "salary" | "electricity" | "maintenance" | "other";

export interface Member {
  id: string;
  gym_id: string;
  member_id: string;
  qr_token: string;
  full_name: string;
  phone: string;
  email: string | null;
  plan_id: string | null;
  plan_name: string | null;
  start_date: string;
  expiry_date: string;
  custom_price: number | null;
  status: MemberStatus;
  is_blocked: boolean;
  total_visits: number;
  last_visit_at: string | null;
  created_at: string;
}

export interface Payment {
  id: string;
  gym_id: string;
  member_id: string;
  amount: number;
  payment_mode: PaymentMode;
  status: PaymentStatus;
  transaction_id: string | null;
  plan_name: string | null;
  created_at: string;
}

export interface PaymentWithMember extends Payment {
  member: { full_name: string; member_id: string } | null;
}

export interface Expense {
  id: string;
  gym_id: string;
  category: ExpenseCategory;
  amount: number;
  description: string | null;
  expense_date: string;
  created_at: string;
}

export interface Attendance {
  id: string;
  gym_id: string;
  member_id: string;
  check_in_at: string;
  source: "qr" | "manual";
}

export interface AttendanceWithMember extends Attendance {
  member: { full_name: string; member_id: string; status: MemberStatus } | null;
}

export interface MembershipPlan {
  id: string;
  gym_id: string;
  name: string;
  duration_days: number;
  price: number;
  is_active: boolean;
}

// Hooks
export function useMembers() {
  const { gymId } = useAuth();

  return useQuery({
    queryKey: ["members", gymId],
    queryFn: async () => {
      if (!gymId) return [];
      
      const { data, error } = await supabase
        .from("members")
        .select("*")
        .eq("gym_id", gymId)
        .is("deleted_at", null)
        .order("created_at", { ascending: false });

      if (error) throw error;
      return (data || []) as Member[];
    },
    enabled: !!gymId,
  });
}

export function useCreateMember() {
  const { gymId } = useAuth();
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: async (member: {
      full_name: string;
      phone: string;
      email?: string;
      plan_id?: string;
      plan_name?: string;
      expiry_date: string;
      custom_price?: number;
    }) => {
      if (!gymId) throw new Error("No gym selected");

      // member_id and qr_token are auto-generated by database triggers
      const insertData = {
        gym_id: gymId,
        full_name: member.full_name,
        phone: member.phone,
        email: member.email || null,
        plan_id: member.plan_id || null,
        plan_name: member.plan_name || null,
        expiry_date: member.expiry_date,
        custom_price: member.custom_price || null,
        member_id: '', // Will be overwritten by trigger
        qr_token: '', // Will be overwritten by trigger
      };

      const { data, error } = await supabase
        .from("members")
        .insert([insertData])
        .select()
        .single();

      if (error) throw error;
      return data;
    },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ["members", gymId] });
      toast.success("Member added successfully!");
    },
    onError: (error: Error) => {
      toast.error(error.message);
    },
  });
}

