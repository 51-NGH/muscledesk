export function useDashboardStats() {
  const { gymId } = useAuth();

  return useQuery({
    queryKey: ["dashboard_stats", gymId],
    queryFn: async () => {
      if (!gymId) return null;

      // Get member counts
      const { data: members } = await supabase
        .from("members")
        .select("id, status")
        .eq("gym_id", gymId)
        .is("deleted_at", null);

      const totalMembers = members?.length || 0;
      const activeMembers = members?.filter((m) => m.status === "active").length || 0;
      const expiringMembers = members?.filter((m) => m.status === "expiring_soon").length || 0;
      const expiredMembers = members?.filter((m) => m.status === "expired").length || 0;

      // Get today's attendance
      const today = new Date().toISOString().split("T")[0];
      const { data: todayAttendance } = await supabase
        .from("attendance")
        .select("id")
        .eq("gym_id", gymId)
        .gte("check_in_at", `${today}T00:00:00`)
        .lt("check_in_at", `${today}T23:59:59`);

      // Get this month's revenue
      const startOfMonth = new Date();
      startOfMonth.setDate(1);
      startOfMonth.setHours(0, 0, 0, 0);

      const { data: monthPayments } = await supabase
        .from("payments")
        .select("amount")
        .eq("gym_id", gymId)
        .eq("status", "completed")
        .gte("created_at", startOfMonth.toISOString());

      const monthlyRevenue = monthPayments?.reduce((sum, p) => sum + Number(p.amount), 0) || 0;

      // Get this month's expenses
      const { data: monthExpenses } = await supabase
        .from("expenses")
        .select("amount")
        .eq("gym_id", gymId)
        .gte("expense_date", startOfMonth.toISOString().split("T")[0]);

      const monthlyExpenses = monthExpenses?.reduce((sum, e) => sum + Number(e.amount), 0) || 0;

      return {
        totalMembers,
        activeMembers,
        expiringMembers,
        expiredMembers,
        todayAttendance: todayAttendance?.length || 0,
        monthlyRevenue,
        monthlyExpenses,
        profit: monthlyRevenue - monthlyExpenses,
      };
    },
    enabled: !!gymId,
  });
}
